export function cloneLineItems(lineItems: PurchaseOrderLineItem[]) {
  return lineItems.map((lineItem) => ({ ...lineItem }))
}

export function calculatePurchaseOrderTotal(
  lineItems: PurchaseOrderLineItem[],
) {
  return lineItems.reduce((total, lineItem) => total + lineItem.amount, 0)
}

