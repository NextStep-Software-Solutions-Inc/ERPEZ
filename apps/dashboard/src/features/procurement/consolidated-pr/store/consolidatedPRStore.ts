export type ConsolidatedPRItem = {
  id: string // Format: `${prId}-${itemName}-${unit}`
  prId: string
  prNumber?: string
  prOffice: string
  itemName: string
  unit: string
  qty: number
  unitPrice: number
  totalAmount: number
  category: string
  prType: 'non-cse' | 'out-of-stock'
  month: string
  fund: string
  // For out-of-stock items only
  totalRequired?: number
  currentTotal?: number
  deficit?: number
}

export type ConsolidatedPR = {
  id: string
  date: string // YYYY-MM-DD
  prNumber?: string // Generated PR number for the consolidated PR
  description?: string
  purpose?: string
  status: 'DRAFT' | 'APPROVED/FOR BAC UTILIZATION'
  selectedPRItems: Array<ConsolidatedPRItem>
  itemMOPs?: Record<string, { mop?: string; allowPartial?: boolean }> // key: item.id
  endUser?: string
  totalAmount?: number
}

interface ConsolidatedPRStore {
  consolidatedPRs: Array<ConsolidatedPR>
  setConsolidatedPRs: (prs: Array<ConsolidatedPR>) => void
  addConsolidatedPR: (pr: ConsolidatedPR) => void
  updateConsolidatedPR: (id: string, pr: Partial<ConsolidatedPR>) => void
  deleteConsolidatedPR: (id: string) => void

  // Get approved consolidated PRs for RFQ
  getApprovedConsolidatedPRs: () => Array<ConsolidatedPR>
}

