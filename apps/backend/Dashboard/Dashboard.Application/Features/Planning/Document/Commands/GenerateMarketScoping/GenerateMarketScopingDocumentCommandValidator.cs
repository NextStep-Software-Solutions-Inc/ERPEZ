using FluentValidation;

namespace ERPEZ.Application.Features.Planning.Document.Commands.GenerateMarketScoping;

public class GenerateMarketScopingDocumentCommandValidator 
    : AbstractValidator<GenerateMarketScopingDocumentCommand>
{
    public GenerateMarketScopingDocumentCommandValidator()
    {
        RuleFor(x => x.MarketScopingId)
            .NotEmpty()
            .WithMessage("Market Scoping ID is required.");

        RuleFor(x => x.Format)
            .IsInEnum()
            .WithMessage("A valid export format (PDF or Excel) is required.");

        RuleFor(x => x.GeneratedBy)
            .NotEmpty()
            .WithMessage("Generated by (user identity) is required.");
    }
}
