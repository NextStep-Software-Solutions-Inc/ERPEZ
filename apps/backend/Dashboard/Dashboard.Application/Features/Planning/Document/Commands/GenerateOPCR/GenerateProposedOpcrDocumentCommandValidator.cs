using FluentValidation;

namespace ERPEZ.Application.Features.Planning.Document.Commands.GenerateOPCR;

public class GenerateProposedOpcrDocumentCommandValidator 
    : AbstractValidator<GenerateProposedOpcrDocumentCommand>
{
    public GenerateProposedOpcrDocumentCommandValidator()
    {
        RuleFor(x => x.OPCRId)
            .NotEmpty()
            .WithMessage("OPCR ID is required.");

        RuleFor(x => x.Format)
            .IsInEnum()
            .WithMessage("A valid export format (PDF or Excel) is required.");

        RuleFor(x => x.GeneratedBy)
            .NotEmpty()
            .WithMessage("Generated by (user identity) is required.");
    }
}