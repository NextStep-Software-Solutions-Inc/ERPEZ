using FluentValidation;

namespace ERPEZ.Application.Features.Planning.Document.Commands.GeneratePPMP;

public class GeneratePpmpDocumentCommandValidator 
    : AbstractValidator<GeneratePpmpDocumentCommand>
{
    public GeneratePpmpDocumentCommandValidator()
    {
        RuleFor(x => x.PpmpId)
            .NotEmpty()
            .WithMessage("PPMP ID is required.");

        RuleFor(x => x.Format)
            .IsInEnum()
            .WithMessage("A valid export format (PDF or Excel) is required.");

        RuleFor(x => x.GeneratedBy)
            .NotEmpty()
            .WithMessage("Generated by (user identity) is required.");
    }
}