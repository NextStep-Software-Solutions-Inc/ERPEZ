using FluentValidation;

namespace ERPEZ.Application.Features.Planning.Document.Commands.GenerateConsolidatedOPCR;

public class GenerateConsolidatedOpcrDocumentCommandValidator
    : AbstractValidator<GenerateConsolidatedOpcrDocumentCommand>
{
    public GenerateConsolidatedOpcrDocumentCommandValidator()
    {
        RuleFor(x => x.ConsolidationId)
            .NotEmpty()
            .WithMessage("Consolidation ID is required.");

        RuleFor(x => x.Format)
            .IsInEnum()
            .WithMessage("A valid export format is required.");

        RuleFor(x => x.GeneratedBy)
            .NotEmpty()
            .WithMessage("Generated by is required.");
    }
}